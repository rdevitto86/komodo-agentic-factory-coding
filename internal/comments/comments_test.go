// containsRule reports whether any finding carries the rule.
func containsRule(findings []Finding, rule string) bool {
	for _, finding := range findings {
		if finding.Rule == rule {
			return true
		}
	}
	return false
}

// writeFile writes a test fixture.
func writeFile(path, body string) error { return os.WriteFile(path, []byte(body), 0o644) }

