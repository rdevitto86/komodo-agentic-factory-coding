// rules returns the rule name of every finding, in order.
func rules(findings []Finding) []string {
	var out []string
	for _, finding := range findings {
		out = append(out, finding.Rule)
	}
	return out
}

func TestResolveFamilyByExtensionAndName(t *testing.T) {
	cases := map[string]string{"a/b.go": familyC, "a/b.py": familyHash, "a/b.sql": familyDash,
		"deploy/Dockerfile": familyHash, "a/b.md": ""}
	for path, want := range cases {
		if got := ResolveFamily(path); got != want {
			t.Errorf("ResolveFamily(%q) = %q, want %q", path, got, want)
		}
	}
}

