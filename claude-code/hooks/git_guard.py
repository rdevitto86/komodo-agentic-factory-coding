# Returns (text, start_offset) pairs -- the offset lets a caller recover this segment's raw, unmasked text
def split_segments(command):
    segments = []
    current = []
    seg_start = 0
    in_squote = False
    in_dquote = False
    in_comment = False
    index = 0
    length = len(command)
    while index < length:
        char = command[index]
        if in_squote:
            current.append(char)
            if char == "'":
                in_squote = False
            index += 1
            continue
        if in_dquote:
            current.append(char)
            if char == "\\" and index + 1 < length:
                current.append(command[index + 1])
                index += 2
                continue
            if char == '"':
                in_dquote = False
            index += 1
            continue
        if in_comment:
            if char == "\n":
                in_comment = False
                segments.append(("".join(current), seg_start))
                current = []
                index += 1
                seg_start = index
                continue
            current.append(char)
            index += 1
            continue
        if char == "#":
            in_comment = True
            current.append(char)
            index += 1
            continue
        if char == "'":
            in_squote = True
            current.append(char)
            index += 1
            continue
        if char == '"':
            in_dquote = True
            current.append(char)
            index += 1
            continue
        if char == "\\" and index + 1 < length:
            current.append(char)
            current.append(command[index + 1])
            index += 2
            continue
        if command.startswith("&&", index) or command.startswith("||", index):
            segments.append(("".join(current), seg_start))
            current = []
            index += 2
            seg_start = index
            continue
        if char in SEGMENT_BOUNDARY_CHARS:
            segments.append(("".join(current), seg_start))
            current = []
            index += 1
            seg_start = index
            continue
        current.append(char)
        index += 1
    segments.append(("".join(current), seg_start))
    return segments


# tokens is now raw shell_words, not the masked segment -- a $()/backtick destination reaches expand_word unblanked
def parse_cp_mv_target(tokens):
    # cp/mv -t DIR (or --target-directory[=DIR]) names the real
    # destination out of order; everything else stays positional.
    index = 0
    target_dir = None
    positional = []
    while index < len(tokens):
        token = tokens[index]
        if token in CP_MV_TARGET_FLAGS:
            if index + 1 < len(tokens):
                target_dir = expand_word(tokens[index + 1])
            index += 2
            continue
        if token.startswith("--target-directory="):
            target_dir = expand_word(token.split("=", 1)[1])
            index += 1
            continue
        if token.startswith("-") and token != "-":
            index += 1
            continue
        positional.append(expand_word(token))
        index += 1
    return target_dir, positional


# settings.json and BACKLOG.md need Edit/Write-only writes, closing the reviewer's Bash side door
GIT_GUARD_ONLY_EXTENSIONS = {".json", ".md"}


def matches_guarded_family(token):
    cleaned = token.strip("\"'")
    base = os.path.basename(cleaned)
    if base in FILENAME_FAMILY:
        return True
    _, ext = os.path.splitext(base)
    ext = ext.lower()
    return ext in EXTENSION_FAMILY or ext in GIT_GUARD_ONLY_EXTENSIONS


def repo_root_of(cwd):
    if not cwd or not os.path.isdir(cwd):
        return None
    try:
        result = subprocess.run(
            ["git", "-C", cwd, "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    top = result.stdout.strip()
    return os.path.realpath(top) if top else None


# repo root walks up from the resolved target, not cwd -- an absolute target can land in a repo even if cwd doesn't
def is_guarded_path(token, cwd):
    if not matches_guarded_family(token):
        return False
    cleaned = token.strip("\"'")
    base_dir = cwd or os.getcwd()
    absolute = cleaned if os.path.isabs(cleaned) else os.path.join(base_dir, cleaned)
    resolved = os.path.realpath(absolute)
    # the target may not exist yet -- start the walk from its parent directory in that case
    start = resolved if os.path.isdir(resolved) else os.path.dirname(resolved)
    repo_root = repo_root_of(start)
    if repo_root is None:
        return False
    try:
        return os.path.commonpath([resolved, repo_root]) == repo_root
    except ValueError:
        return False


def blank(text):
    return re.sub(r"[^\n]", " ", text)


def mask_data(command):
    # heredoc bodies and quoted spans are data, not shell syntax
    masked = HEREDOC.sub(lambda m: m.group(1) + blank(m.group(3)) + m.group(4), command)
    return QUOTED.sub(lambda m: blank(m.group(0)), masked)


def tokenize(segment):
    try:
        return shlex.split(segment)
    except ValueError:
        return segment.split()


# shlex already resolves every quoting shape ('-i', -'i', -"i" ...) to the bare token -- rejoin beats a per-shape regex
def normalize_shell_words(segment):
    return " ".join(tokenize(segment))


# Splits text[start:end] into shell words, atomic through quotes/$()/backticks; returns (word, abs_start) pairs
def shell_words(text, start, end, terminators=""):
    words = []
    index = start
    word_start = None
    # depth tracks bare "(" since word_start -- only an unmatched ")" ends the word, not a balanced literal paren
    paren_depth = 0
    while index < end:
        char = text[index]
        if char == ")":
            if paren_depth > 0:
                paren_depth -= 1
                if word_start is None:
                    word_start = index
                index += 1
                continue
            if char in terminators:
                if word_start is not None:
                    words.append((text[word_start:index], word_start))
                    word_start = None
                break
            if word_start is None:
                word_start = index
                paren_depth = 0
            index += 1
            continue
        if char in terminators or char.isspace():
            if word_start is not None:
                words.append((text[word_start:index], word_start))
                word_start = None
            if char in terminators:
                break
            index += 1
            continue
        if word_start is None:
            word_start = index
            paren_depth = 0
        if char == "\\" and index + 1 < end:
            index += 2
            continue
        if char == "'":
            index += 1
            while index < end and text[index] != "'":
                index += 1
            index = min(index + 1, end)
            continue
        if char == '"':
            index += 1
            while index < end:
                if text[index] == "\\" and index + 1 < end:
                    index += 2
                    continue
                if text[index] == '"':
                    index += 1
                    break
                index += 1
            continue
        if char == "`":
            stop = find_backtick_end(text, index + 1)
            index = min(stop + 1, end)
            continue
        if char == "$" and text.startswith("$(", index):
            stop = find_paren_end(text, index + 2)
            index = min(stop + 1, end)
            continue
        if char == "(":
            paren_depth += 1
            index += 1
            continue
        index += 1
    if word_start is not None:
        words.append((text[word_start:index], word_start))
    return words


# well past real nesting -- gives adversarial input a deterministic DENY instead of a RecursionError hitting fail-open
MAX_SCAN_DEPTH = 50


# raised by any depth-bound recursive scanner below so an outer caller can turn "too deep to analyze" into a DENY
class ScanDepthExceeded(Exception):
    pass


# can't execute a captured command -- "echo ARGS" resolves to ARGS, anything else falls back to a matching arg
def resolve_command_output(inner, depth=0):
    if depth > MAX_SCAN_DEPTH:
        raise ScanDepthExceeded()
    words = shell_words(inner, 0, len(inner))
    if not words:
        return ""
    expanded = [expand_word(word, depth + 1) for word, _ in words]
    if expanded[0] == "echo":
        return " ".join(expanded[1:])
    match = next((token for token in expanded[1:] if matches_guarded_family(token)), None)
    return match if match is not None else " ".join(expanded)


# fully dequotes a word, mid-word split included, and resolves every $()/backtick piece it holds, nested or not
def expand_word(word, depth=0):
    if depth > MAX_SCAN_DEPTH:
        raise ScanDepthExceeded()
    out = []
    index = 0
    length = len(word)
    while index < length:
        char = word[index]
        if char == "\\" and index + 1 < length:
            out.append(word[index + 1])
            index += 2
            continue
        if char == "'":
            end = word.find("'", index + 1)
            end = length if end == -1 else end
            out.append(word[index + 1:end])
            index = min(end + 1, length)
            continue
        if char == '"':
            index += 1
            buf = []
            while index < length and word[index] != '"':
                if word[index] == "\\" and index + 1 < length and word[index + 1] in "\"\\$`":
                    buf.append(word[index + 1])
                    index += 2
                    continue
                buf.append(word[index])
                index += 1
            index = min(index + 1, length)
            out.append(expand_word("".join(buf), depth + 1))
            continue
        if char == "`":
            stop = find_backtick_end(word, index + 1)
            inner = unescape_nested_backticks(word[index + 1:stop])
            out.append(resolve_command_output(inner, depth + 1))
            index = min(stop + 1, length)
            continue
        if char == "$" and word.startswith("$(", index):
            stop = find_paren_end(word, index + 2)
            out.append(resolve_command_output(word[index + 2:stop], depth + 1))
            index = min(stop + 1, length)
            continue
        out.append(char)
        index += 1
    return "".join(out)


def resolve_guard_target(word, cwd):
    target = expand_word(word)
    return target if is_guarded_path(target, cwd) else None


REDIRECT_OP = re.compile(r"^(&>{1,2}|\d*>{1,2}(&\d+)?|\d*<)")


def strip_redirects(tokens):
    # shlex has no concept of shell redirection, so `git merge main 2>&1`
    # tokenizes "2>&1" as an ordinary word — miscounting positional args
    # for anything downstream that checks how many a subcommand got.
    result = []
    skip_next = False
    for token in tokens:
        if skip_next:
            skip_next = False
            continue
        match = REDIRECT_OP.match(token)
        if match is None:
            result.append(token)
            continue
        if match.end() != len(token):
            continue
        skip_next = True
    return result


def strip_env_assignments(tokens):
    index = 0
    while index < len(tokens) and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", tokens[index]):
        index += 1
    return tokens[index:]


def strip_leading_flags(tokens, value_flags):
    index = 0
    while index < len(tokens) and tokens[index].startswith("-"):
        flag = tokens[index]
        index += 1
        if flag in value_flags:
            index += 1
            continue
        if "=" in flag:
            continue
        # An option we don't have on record: if what follows doesn't look
        # like the wrapped command itself, assume it's this flag's value
        # rather than mis-starting the inner command at that token.
        if index < len(tokens):
            nxt = tokens[index]
            if not nxt.startswith("-") and os.path.basename(nxt) not in MONITORED_COMMANDS:
                index += 1
    return tokens[index:]


def subcommand_of(tokens, value_flags):
    index = 1
    while index < len(tokens):
        token = tokens[index]
        if token in value_flags:
            index += 2
            continue
        if token.startswith("-"):
            index += 1
            continue
        return token, tokens[index + 1:]
    return None, []


def leading_word(segment):
    tokens = strip_env_assignments(tokenize(segment))
    return os.path.basename(tokens[0]) if tokens else ""


def current_branch(cwd):
    if not cwd or not os.path.isdir(cwd):
        return None
    try:
        result = subprocess.run(
            ["git", "-C", cwd, "symbolic-ref", "--short", "HEAD"],
            capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip() or None


def is_protected(ref):
    ref = ref.strip().strip("\"'")
    if ref.startswith("refs/heads/"):
        ref = ref[len("refs/heads/"):]
    if ref in PROTECTED_BRANCHES:
        return True
    return ref.startswith(PROTECTED_PREFIXES)


def push_violation(args, cwd):
    positional = []
    for arg in args:
        if arg in PUSH_FORCE_FLAGS or arg.startswith("--force-with-lease=") or arg.startswith("--force-if-includes="):
            return "git push %s rewrites published history" % arg
        if arg in PUSH_BANNED_FLAGS:
            return "git push %s is denied" % arg
        if not arg.startswith("-"):
            positional.append(arg)
    if len(positional) < 2:
        return "git push needs an explicit remote and branch — git push -u origin <branch>"
    for spec in positional[1:]:
        if spec.startswith("+"):
            return "a + refspec force-pushes; push without it"
        if spec.startswith(":"):
            return "git push :<ref> deletes a remote branch"
        source, _, destination = spec.partition(":")
        destination = destination or source
        if destination in ("HEAD", ""):
            destination = current_branch(cwd) or ""
            if not destination:
                return "cannot resolve HEAD to a branch — name the destination explicitly"
        if is_protected(destination):
            return "git push to %s is denied — open a pull request instead" % destination
    return None


def commit_violation(args, cwd, has_cd):
    for arg in args:
        if arg in COMMIT_BANNED_FLAGS:
            return "git commit %s skips a gate or rewrites a commit" % arg
    if BANNED_TRAILER.search(" ".join(args)):
        return TRAILER_FINDING
    if has_cd:
        return "a cd earlier in this command makes the current branch unknowable"
    branch = current_branch(cwd)
    if branch is None:
        return "cannot resolve the current branch — refusing to commit"
    if is_protected(branch):
        return "git commit on %s is denied — create a branch first" % branch
    return None


def switch_violation(args):
    created = None
    index = 0
    while index < len(args):
        arg = args[index]
        if arg in SWITCH_BANNED_FLAGS:
            return "git switch %s is denied" % arg
        if arg in ("-c", "--create"):
            created = args[index + 1] if index + 1 < len(args) else ""
            index += 2
            continue
        index += 1
    if created is not None and not BRANCH_NAME.match(created):
        return "branch name '%s' must match <type>/<kebab-case>" % created
    return None


def merge_violation(subcommand, args, cwd):
    if subcommand == "pull":
        if "--ff-only" in args:
            return None
        return "git pull is allowed only with --ff-only — use git fetch + git merge for a real sync"
    if any(flag in args for flag in MERGE_SAFE_FLAGS):
        return None
    for flag in MERGE_BANNED_FLAGS:
        if flag in args:
            return "git merge %s auto-resolves without a visible conflict" % flag
    branch = current_branch(cwd)
    if branch and is_protected(branch):
        return "git merge on %s, a protected branch — landing into it stays the user's job" % branch
    positional = [arg for arg in args if not arg.startswith("-")]
    if len(positional) != 1:
        return "git merge only takes one target: the protected base branch, to sync before a human merges the PR"
    target = positional[0]
    bare = target[len("origin/"):] if target.startswith("origin/") else target
    if not is_protected(bare):
        return "git merge %s isn't the protected base branch" % target
    return None


def git_violation(subcommand, args, cwd, has_cd):
    if subcommand is None:
        return None
    if not PUBLISH_ENABLED:
        if subcommand in PUBLISH_VERBS:
            return "git %s changes repository state" % subcommand
        if subcommand == "branch":
            positional = [arg for arg in args if not arg.startswith("-")]
            if positional:
                return "git branch %s creates a branch" % positional[0]
    if subcommand == "push":
        return push_violation(args, cwd)
    if subcommand == "commit":
        return commit_violation(args, cwd, has_cd)
    if subcommand == "switch":
        return switch_violation(args)
    if subcommand == "add":
        for arg in args:
            if arg in ADD_BANNED_FLAGS:
                return "git add %s is interactive and cannot complete here" % arg
        return None
    if subcommand in ("merge", "pull"):
        return merge_violation(subcommand, args, cwd)
    if subcommand == "stash":
        positional = [arg for arg in args if not arg.startswith("-")]
        if positional and positional[0] in ("list", "show"):
            return None  # explicit read-only mode; bare `git stash` defaults to push/save
        if not PUBLISH_ENABLED:
            return "git stash changes repository state"
        if positional and positional[0] in STASH_MUTATING_FLAGS:
            return "git stash %s discards saved state" % positional[0]
        return None
    if subcommand == "branch":
        positional = [arg for arg in args if not arg.startswith("-")]
        for flag in MUTATING_FLAGS["branch"]:
            if flag in args:
                return "git branch %s changes repository state" % flag
        if positional and not BRANCH_NAME.match(positional[0]):
            return "branch name '%s' must match <type>/<kebab-case>" % positional[0]
        return None
    if subcommand not in READ_ONLY_GIT:
        return "git %s changes repository state" % subcommand
    if subcommand == "config":
        positional = [arg for arg in args if not arg.startswith("-")]
        if len(positional) >= 2:
            return "git config %s sets a value" % positional[0]
    mutators = MUTATING_FLAGS.get(subcommand)
    if not mutators:
        return None
    for arg in args:
        if arg in mutators:
            return "git %s %s changes repository state" % (subcommand, arg)
    return None


def current_branch_pr_number():
    try:
        result = subprocess.run(
            ["gh", "pr", "view", "--json", "number", "-q", ".number"],
            capture_output=True, text=True, timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    value = result.stdout.strip()
    return value or None


def gh_violation(tokens):
    group, rest = subcommand_of(tokens, GH_GLOBAL_VALUE_FLAGS)
    if group is None:
        return None
    if group == "api":
        for token in tokens:
            if token in GH_API_WRITE_FLAGS or token.startswith("--method="):
                return "gh api write requests are denied"
        return None
    if group not in GH_ALLOWED:
        return "gh %s is denied" % group
    allowed = GH_ALLOWED[group]
    if allowed is None:
        return None
    subcommand = next((arg for arg in rest if not arg.startswith("-")), "")
    if subcommand not in allowed:
        return "gh %s %s is denied" % (group, subcommand or "<none>")
    if group == "pr" and subcommand in GH_PR_SCOPED_ACTIONS:
        after = rest[rest.index(subcommand) + 1:]
        target = next((arg for arg in after if not arg.startswith("-")), None)
        own_pr = current_branch_pr_number()
        if own_pr is None:
            return "gh pr %s couldn't confirm this branch's own PR number" % subcommand
        if target and target != own_pr:
            return "gh pr %s %s reaches a PR that isn't this branch's own (#%s)" % (subcommand, target, own_pr)
    return None


def scan_segment(segment, findings, cwd, has_cd, full_command, seg_start, seg_end, depth=0):
    tokens = strip_redirects(strip_env_assignments(tokenize(segment)))
    if not tokens:
        return
    # a bare (cmd ...) subshell glues its "(" onto the first word -- stripped only for command identification
    command = os.path.basename(tokens[0].lstrip("("))
    if command in SHELL_WRAPPERS:
        for index, token in enumerate(tokens):
            if token == "-c" and index + 1 < len(tokens):
                scan_command(tokens[index + 1], findings, cwd, depth + 1)
        return
    if command == "eval":
        inner = tokens[1:]
        if inner:
            scan_command(" ".join(inner), findings, cwd, depth + 1)
        return
    if command in PASSTHROUGH_WRAPPERS:
        inner = strip_leading_flags(tokens[1:], PASSTHROUGH_VALUE_FLAGS[command])
        if inner:
            scan_command(" ".join(inner), findings, cwd, depth + 1)
        return
    if command == "tee":
        # tokens loses a $()/backtick arg to blanking -- scan raw shell_words against full_command instead
        for word, _ in shell_words(full_command, seg_start, seg_end, REDIRECT_WORD_TERMINATORS):
            target = resolve_guard_target(word, cwd)
            if target:
                findings.append("tee writing to %s bypasses the comment guard" % target)
                break
        return
    if command in ("sed", "perl", "python", "python3"):
        # raw segment text gated on its own leading command -- a quoted mention elsewhere never reaches here
        raw_segment = full_command[seg_start:seg_end]
        # normalized once here -- shlex strips every quoting shape around -i before the -i regexes ever run
        normalized_segment = normalize_shell_words(raw_segment)
        if command == "sed" and INPLACE_SED.search(normalized_segment):
            findings.append("sed -i rewrites files in place, bypassing the comment guard")
        elif command == "perl" and INPLACE_PERL.search(normalized_segment):
            findings.append("perl -i rewrites files in place, bypassing the comment guard")
        elif command in ("python", "python3") and PYTHON_WRITE.search(raw_segment):
            findings.append("python -c opening a file for writing bypasses the comment guard")
        return
    if command in ("cp", "mv"):
        # raw shell_words on full_command, not tokens -- tokens is masked, blanking any $()/backtick destination
        raw_words = strip_redirects(strip_env_assignments(
            [word for word, _ in shell_words(full_command, seg_start, seg_end, REDIRECT_WORD_TERMINATORS)]
        ))
        target_dir, positional = parse_cp_mv_target(raw_words[1:])
        if target_dir is not None:
            if is_guarded_path(target_dir, cwd):
                findings.append("%s writing to %s bypasses the comment guard" % (command, target_dir))
                return
            for source in positional:
                if is_guarded_path(source, cwd):
                    findings.append("%s writing to %s bypasses the comment guard" % (command, target_dir))
                    break
            return
        if not positional:
            return
        destination = positional[-1]
        sources = positional[:-1]
        dest_clean = destination.strip("\"'")
        stripped = dest_clean.rstrip("/")
        _, dest_ext = os.path.splitext(stripped)
        dest_is_dir = (
            dest_clean.endswith("/")
            or (bool(stripped) and os.path.isdir(stripped))
            or (bool(stripped) and not dest_ext and not os.path.isfile(stripped))
        )
        if dest_is_dir:
            for source in sources:
                if is_guarded_path(source, cwd):
                    findings.append("%s writing to %s bypasses the comment guard" % (command, destination))
                    break
        elif is_guarded_path(destination, cwd):
            findings.append("%s writing to %s bypasses the comment guard" % (command, destination))
        return
    if command == "git":
        subcommand, args = subcommand_of(tokens, GIT_GLOBAL_FLAGS_WITH_VALUE)
        scoped = cwd
        for index, token in enumerate(tokens):
            if token == "-C" and index + 1 < len(tokens):
                scoped = tokens[index + 1]
        violation = git_violation(subcommand, args, scoped, has_cd)
        if violation:
            findings.append(violation)
        return
    if command == "gh":
        violation = gh_violation(tokens)
        if violation:
            findings.append(violation)
        return


def scan_command(command, findings, cwd, depth=0):
    if depth > MAX_SCAN_DEPTH:
        findings.append("command could not be safely analyzed")
        return
    try:
        _scan_command_at_depth(command, findings, cwd, depth)
    except ScanDepthExceeded:
        # word-expansion recursion (expand_word <-> resolve_command_output) hit the bound via a redirect/tee/cp/mv target word
        findings.append("command could not be safely analyzed")


def _scan_command_at_depth(command, findings, cwd, depth):
    masked, substitutions = extract_substitutions(command)
    raw_segments = split_segments(masked)
    segments = []
    for text, start in raw_segments:
        stripped = text.strip()
        if not stripped:
            continue
        abs_start = start + (len(text) - len(text.lstrip()))
        # start+len(text), not abs_start+len(stripped) -- a trailing blanked substitution is stripped away otherwise
        abs_end = start + len(text)
        segments.append((stripped, abs_start, abs_end))
    has_cd = any(leading_word(stripped) == "cd" for stripped, _, _ in segments)
    for stripped, abs_start, abs_end in segments:
        scan_segment(stripped, findings, cwd, has_cd, command, abs_start, abs_end, depth)
    # recursing into each substitution catches a mutating command hidden in backticks/$() -- else it slips past as inert text
    for substitution in substitutions:
        if substitution.strip():
            scan_command(substitution, findings, cwd, depth + 1)

    # sed/perl/python-write moved to scan_segment (see there); trailer stays on raw command -- it can live in a quoted -m
    if GIT_MESSAGE_CALL.search(command) and BANNED_TRAILER.search(command):
        findings.append(TRAILER_FINDING)

    # quotes/heredocs blanked so a real `>` inside one is not read as an operator; target still resolves from raw command
    guard_source = mask_data(command)
    for match in REDIRECT_OPERATOR.finditer(guard_source):
        words = shell_words(command, match.end(), len(command), REDIRECT_WORD_TERMINATORS)
        if not words:
            continue
        word, _ = words[0]
        target = resolve_guard_target(word, cwd)
        if target:
            findings.append("redirecting output into %s bypasses the comment guard" % target)


def respond_deny(reason):
    payload = {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }
    sys.stdout.write(json.dumps(payload))
    sys.exit(0)


# a crash in here is our own broken analysis, not a policy decision -- main() catches this and fails open
def analyze(payload):
    if payload.get("tool_name") != "Bash":
        return []
    command = (payload.get("tool_input") or {}).get("command", "")
    if not command:
        return []
    findings = []
    scan_command(command, findings, payload.get("cwd") or os.getcwd())
    return findings


def main():
    try:
        payload = json.loads(sys.stdin.read())
        findings = analyze(payload)
    except BaseException as error:
        sys.stderr.write(
            "git guard is broken: %s: %s\nFailing open -- allowing this command through.\n"
            % (type(error).__name__, error)
        )
        sys.exit(0)

    if not findings:
        sys.exit(0)

    unique = []
    for item in findings:
        if item not in unique:
            unique.append(item)

    lines = ["BLOCKED. Nothing ran.", ""]
    lines.extend("    %s" % item for item in unique)
    lines.extend([
        "",
        "The agent branches, commits, pushes its own branch, opens a PR, and",
        "may merge its protected base into its own branch to resolve conflicts,",
        "or pull it with --ff-only. main/master/trunk/prod/production/",
        "release/*/hotfix/* stay off limits, and so do landing a branch into",
        "one, rebases, non-ff-only pulls, force-push, --amend, and history",
        "rewrites. Run this yourself if you intended it.",
    ])
    respond_deny("\n".join(lines))


if __name__ == "__main__":
    main()
