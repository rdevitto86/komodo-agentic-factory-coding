def scan_masked_span(command, start, is_terminator):
    index = start
    length = len(command)
    in_squote = False
    in_dquote = False
    while index < length:
        char = command[index]
        if in_squote:
            if char == "'":
                in_squote = False
            index += 1
            continue
        if in_dquote:
            if char == "\\" and index + 1 < length:
                index += 2
                continue
            if char == '"':
                in_dquote = False
            index += 1
            continue
        if char == "\\" and index + 1 < length:
            index += 2
            continue
        if char == "'":
            in_squote = True
            index += 1
            continue
        if char == '"':
            in_dquote = True
            index += 1
            continue
        if is_terminator(char):
            return index
        index += 1
    return length


def find_backtick_end(command, start):
    return scan_masked_span(command, start, lambda char: char == "`")


def unescape_nested_backticks(text):
    return text.replace("\\`", "`")


def find_paren_end(command, start):
    depth = [1]

    def is_terminator(char):
        if char == "(":
            depth[0] += 1
            return False
        if char == ")":
            depth[0] -= 1
            return depth[0] == 0
        return False

    return scan_masked_span(command, start, is_terminator)


# blanks captured substitution text in place instead of a placeholder token -- keeps offsets aligned for split_segments
def capture_and_mask(command, masked, substitutions, index, finder, offset, unescape=None):
    length = len(command)
    end = finder(command, index + offset)
    text = command[index + offset:end]
    substitutions.append(unescape(text) if unescape else text)
    stop = min(end + 1, length)
    for i in range(index, stop):
        if masked[i] != "\n":
            masked[i] = " "
    return stop


